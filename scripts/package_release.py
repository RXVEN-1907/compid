#!/usr/bin/env python3
"""Deterministic release packaging for compid, portable to every runner.

Stages the same archive layout scripts/dist.sh has always produced and
writes either a .tar.gz (unix targets) or a .zip (Windows targets), plus a
.sha256 sidecar. Both formats are written with fixed metadata - epoch
mtimes, root owner, normalized permissions, sorted entries, timestamp-free
gzip - so re-running the packager over the same inputs is byte-stable.

Usage:
  scripts/package_release.py --name compid-0.2.0-x86_64-unknown-linux-gnu \
      --binary target/x86_64-unknown-linux-gnu/release/compid \
      --completions-dir completions-gen [--format tar.gz] [--out dist]

The binary keeps its name inside the archive: "compid" for tar.gz, "compid.exe"
for zip. The completions directory must already hold the four generated
completion files (produced by a host build, see .github/workflows/release.yml);
the README for them lives here so every archive ships identical instructions.
"""
import argparse
import gzip
import hashlib
import shutil
import tarfile
import tempfile
import time
import zipfile
from io import BytesIO
from pathlib import Path

COMPLETIONS_README = """Shell completions for compid.

Generated by the build that produced this archive; the script covers the
subcommands and flags of exactly that build, so reinstall after upgrading.

  bash         install as ~/.local/share/bash-completion/completions/compid
               (create the directory first if it does not exist)
  zsh          install as ~/.zfunc/_compid, with ~/.zfunc in fpath before
               compinit runs
  fish         install as ~/.config/fish/completions/compid.fish
  powershell   dot-source from your $PROFILE, or append to it

docs/cli.md in this archive carries the same instructions with more detail.
"""

COMPLETION_NAMES = {
    "bash": "compid.bash",
    "zsh": "_compid",
    "fish": "compid.fish",
    "powershell": "compid.ps1",
}


def stage(name: str, binary: Path, completions_dir: Path, repo: Path, fmt: str) -> tuple[Path, Path]:
    """Assemble the archive root; returns (staging dir, archive root)."""
    stage_root = Path(tempfile.mkdtemp(prefix="compid-pkg-"))
    root = stage_root / name
    (root / "completions").mkdir(parents=True)
    (root / "docs").mkdir()

    # The archive entry is always "compid" (tar.gz) or "compid.exe" (zip),
    # whatever the building host named the file.
    exe_name = "compid.exe" if fmt == "zip" else "compid"
    shutil.copy2(binary, root / exe_name)
    for shell, out in COMPLETION_NAMES.items():
        src = completions_dir / out
        if not src.is_file():
            raise SystemExit(f"missing generated completion: {src}")
        shutil.copy2(src, root / "completions" / out)
    (root / "completions" / "README").write_text(COMPLETIONS_README, encoding="utf-8")
    for pattern in ("*.md", "*.svg", "*.1"):
        for f in sorted((repo / "docs").glob(pattern)):
            shutil.copy2(f, root / "docs" / f.name)
    for f in ("LICENSE", "README.md", "CHANGELOG.md"):
        src = repo / f
        if not src.is_file():
            raise SystemExit(f"missing {src}")
        shutil.copy2(src, root / f)
    return stage_root, root


def normalize(root: Path, exe: Path) -> None:
    """Fixed permissions so the archive does not depend on the builder's umask."""
    for p in root.rglob("*"):
        p.chmod(0o755 if p.is_dir() else 0o644)
    exe.chmod(0o755)


def sorted_members(root: Path) -> list[Path]:
    return sorted(root.rglob("*"), key=lambda p: (p.is_dir(), str(p.relative_to(root))))


def write_tar_gz(root: Path, name: str, out_dir: Path) -> Path:
    """Fixed tar (GNU format, epoch mtimes, root owner) through a
    timestamp-free gzip stream. Members carry the <name>/ prefix so an
    unpack lands in one directory, matching dist.sh's historical layout."""
    buf = BytesIO()
    with tarfile.open(fileobj=buf, mode="w", format=tarfile.GNU_FORMAT) as tar:
        for p in sorted_members(root):
            ti = tar.gettarinfo(str(p), arcname=f"{name}/{p.relative_to(root).as_posix()}")
            ti.uid = ti.gid = 0
            ti.uname = ti.gname = ""
            ti.mtime = 0
            if p.is_file():
                ti.size = p.stat().st_size
                with p.open("rb") as src:
                    tar.addfile(ti, src)
            else:
                tar.addfile(ti)
    dest = out_dir / f"{name}.tar.gz"
    with dest.open("wb") as f:
        with gzip.GzipFile(fileobj=f, mode="wb", filename="", mtime=0, compresslevel=9) as gz:
            gz.write(buf.getvalue())
    return dest


def write_zip(root: Path, name: str, out_dir: Path) -> Path:
    """Fixed zip: 1980-epoch timestamps, explicit unix permission bits."""
    dest = out_dir / f"{name}.zip"
    with zipfile.ZipFile(dest, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for p in sorted_members(root):
            arc = f"{name}/{p.relative_to(root).as_posix()}"
            zi = zipfile.ZipInfo(arc, date_time=(1980, 1, 1, 0, 0, 0))
            mode = 0o755 if p.is_dir() or p.name == "compid.exe" else 0o644
            zi.external_attr = (mode << 16) | (0x10 if p.is_dir() else 0)
            zi.compress_type = zipfile.ZIP_DEFLATED
            z.writestr(zi, p.read_bytes() if p.is_file() else b"")
    return dest


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main() -> None:
    repo = Path(__file__).resolve().parent.parent
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--name", required=True,
                    help="archive stem, e.g. compid-0.2.0-aarch64-apple-darwin")
    ap.add_argument("--binary", required=True, type=Path, help="built binary to package")
    ap.add_argument("--completions-dir", required=True, type=Path,
                    help="directory holding the four generated completion files")
    ap.add_argument("--format", choices=("tar.gz", "zip"), default="tar.gz")
    ap.add_argument("--out", type=Path, default=Path("dist"))
    args = ap.parse_args()

    if not args.binary.is_file():
        raise SystemExit(f"no binary at {args.binary}")

    args.out.mkdir(parents=True, exist_ok=True)
    stage_root, root = stage(args.name, args.binary.resolve(),
                             args.completions_dir.resolve(), repo, args.format)
    try:
        exe = root / ("compid.exe" if args.format == "zip" else "compid")
        normalize(root, exe)
        t0 = time.time()
        archive = (write_zip(root, args.name, args.out) if args.format == "zip"
                   else write_tar_gz(root, args.name, args.out))
        sidecar = args.out / f"{archive.name}.sha256"
        sidecar.write_text(f"{sha256_file(archive)}  {archive.name}\n", encoding="utf-8")
        print(f"packaged {archive.name} ({archive.stat().st_size // (1024 * 1024)} MiB) "
              f"in {time.time() - t0:.1f}s")
    finally:
        shutil.rmtree(stage_root)


if __name__ == "__main__":
    main()
