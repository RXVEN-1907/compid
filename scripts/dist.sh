#!/usr/bin/env bash
# Release packaging for compid.
#
# Builds the release binary, generates shell completions from it, and hands
# both to scripts/package_release.py, which stages the archive and writes a
# deterministic tarball plus its sha256 under dist/.
#
# Usage: scripts/dist.sh [TARGET-TRIPLE]
#   With no argument, builds and packages for the host (triple taken from
#   rustc -vV). With a triple, builds for that target instead - the rustup
#   target must be installed, and a cross linker, when one is needed, comes
#   from the environment (e.g. CARGO_TARGET_AARCH64_UNKNOWN_LINUX_GNU_LINKER,
#   as wired in .github/workflows/release.yml).
#
# Tarball layout (identical to what package_release.py stages):
#   compid-<version>-<triple>/
#     compid          release binary
#     completions/    compid.bash, _compid, compid.fish, compid.ps1, README
#     docs/           markdown, the architecture diagram (svg), and the man page
#     LICENSE  README.md  CHANGELOG.md

set -euo pipefail

repo="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$repo"

# Version from the [package] table: the first top-of-line `version` key in
# Cargo.toml. Parameter expansion instead of sed, so no escaping surprises.
version_line="$(grep -m1 '^version' Cargo.toml)"
version="${version_line#*\"}"
version="${version%\"*}"

host="$(rustc -vV | awk '/^host:/ {print $2}')"
target="${1:-$host}"

echo "dist: compid $version for $target"

# The host build always happens: its binary generates the completions that
# ship alongside a cross target's binary (a cross binary cannot run here,
# and the generated files must match the CLI of exactly this tree).
cargo build --release
if [ "$target" != "$host" ]; then
    cargo build --release --target "$target"
    binary="target/$target/release/compid"
else
    binary="target/release/compid"
fi

# Completions are generated by a binary that runs on this host. zsh
# completion functions must be named `_compid` to be found on fpath; fish
# wants .fish; powershell ships as .ps1.
completions="dist/completions-$version"
rm -rf dist
mkdir -p "$completions"
for shell in bash zsh fish powershell; do
    case "$shell" in
        zsh)        out="_compid" ;;
        powershell) out="compid.ps1" ;;
        *)          out="compid.$shell" ;;
    esac
    "./target/release/compid" completions "$shell" > "$completions/$out"
done

python3 scripts/package_release.py \
    --name "compid-$version-$target" \
    --binary "$binary" \
    --completions-dir "$completions" \
    --out dist

rm -rf "$completions"

# Self-check: the checksum file must round-trip against the tarball.
( cd dist && sha256sum -c "compid-$version-$target.tar.gz.sha256" )

echo "dist: wrote dist/compid-$version-$target.tar.gz"
ls -lh "dist/compid-$version-$target.tar.gz" "dist/compid-$version-$target.tar.gz.sha256"
