#!/usr/bin/env bash
# Reproducible release packaging for compid.
#
# Builds the release binary, generates shell completions from that binary,
# and assembles a deterministic tarball plus its sha256 under dist/.
#
# Usage: scripts/dist.sh [TARGET-TRIPLE]
#   With no argument, builds and packages for the host (triple taken from
#   rustc -vV). With a triple, builds for that target instead - the rustup
#   target must be installed, and a cross linker, when one is needed, comes
#   from the environment (e.g. CARGO_TARGET_AARCH64_UNKNOWN_LINUX_GNU_LINKER,
#   as wired in .github/workflows/release.yml).
#
# Tarball layout:
#   compid-<version>-<triple>/
#     compid          release binary
#     completions/    compid.bash, _compid, compid.fish, compid.ps1, README
#     docs/           markdown, the architecture diagram (svg), and the man page
#     LICENSE  README.md  CHANGELOG.md
#
# Determinism: staged files get normalized permissions, the archive is
# written with sorted entries, fixed owner/group, and an epoch mtime, and
# gzip runs with -n (no timestamp in the header), so two runs over the same
# tree produce byte-identical tarballs. Requires GNU tar for --sort/--mtime.

set -euo pipefail

repo="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$repo"

# Version from the [package] table: the first top-of-line `version` key in
# Cargo.toml. Parameter expansion instead of sed, so no escaping surprises.
version_line="$(grep -m1 '^version' Cargo.toml)"
version="${version_line#*\"}"
version="${version%\"*}"

host="$(rustc -vV | awk '/^host:/ {print $2}')"
target="${1:-$host}"

echo "dist: compid $version for $target"

if [ "$target" = "$host" ]; then
    binary="target/release/compid"
    cargo build --release
else
    binary="target/$target/release/compid"
    # A cross target's binary cannot execute on this host, so the host build
    # is kept around too: it generates the completions (same source, so the
    # same CLI) that ship alongside the cross binary.
    cargo build --release
    cargo build --release --target "$target"
fi

name="compid-$version-$target"
stage="dist/$name"

# Fresh staging area on every run.
rm -rf dist
mkdir -p "$stage/completions" "$stage/docs"

cp "$binary" "$stage/compid"

# Completions are generated by a binary that runs on this host (the host
# build; for the host target that is the packaged binary itself), so they
# always match the CLI. zsh completion functions must be named `_compid` to
# be found on fpath; fish wants .fish; powershell ships as .ps1.
for shell in bash zsh fish powershell; do
    case "$shell" in
        zsh)        out="_compid" ;;
        powershell) out="compid.ps1" ;;
        *)          out="compid.$shell" ;;
    esac
    "./target/release/compid" completions "$shell" > "$stage/completions/$out"
done

cat > "$stage/completions/README" <<'EOF'
Shell completions for compid.

Generated by the build that produced this archive; the script covers the
subcommands and flags of exactly that build, so reinstall after upgrading.

  bash         install as ~/.local/share/bash-completion/completions/compid
               (create the directory first if it does not exist)
  zsh          install as ~/.zfunc/_compid, with ~/.zfunc in fpath before
               compinit runs
  fish         install as ~/.config/fish/completions/compid.fish
  powershell   dot-source from your $PROFILE, or append to it

docs/cli.md in this archive carries the same instructions with more detail.
EOF

for f in docs/*.md docs/*.svg docs/*.1; do
    if [ -f "$f" ]; then
        cp "$f" "$stage/docs/"
    fi
done

cp LICENSE README.md CHANGELOG.md "$stage/"

# Normalize permissions so the tarball does not depend on the building
# user's umask.
find "$stage" -type d -exec chmod 755 {} +
find "$stage" -type f -exec chmod 644 {} +
chmod 755 "$stage/compid"

tarball="$name.tar.gz"
tar -C dist --sort=name --owner=0 --group=0 --numeric-owner --mtime='@0' \
    -c "$name" | gzip -n > "dist/$tarball"

# Checksum written from inside dist/ so `sha256sum -c` works in place.
( cd dist && sha256sum "$tarball" > "$tarball.sha256" )

# Self-check: the checksum file must round-trip against the tarball.
( cd dist && sha256sum -c "$tarball.sha256" )

echo "dist: wrote dist/$tarball and dist/$tarball.sha256"
ls -lh "dist/$tarball" "dist/$tarball.sha256"
